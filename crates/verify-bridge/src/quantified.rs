//! Module `quantified` implements formal verification of Minimax Saddle Points (Nash Equilibria)
//! and exports quantified formulas ($\forall \mathbf{y} \exists \mathbf{x} \, \dots$) to standardized SMT-LIB2 format.
//!
//! # Mathematical Verification of Local Nash Equilibrium:
//!
//! For a given spin state $\mathbf{s} = (\mathbf{x}^*, \mathbf{y}^*) \in \{-1, +1\}^{N_x + N_y}$:
//!
//! 1. **Minimizer Stability Condition ($\min_{\mathbf{x}} H$):**
//!    For every spin $i \in [0, N_x)$, the energy change upon flipping $s_i \to -s_i$:
//!    $$\Delta H_i^x = 2 s_i \left( \sum_{j=0}^{N-1} J_{ij} s_j + h_i \right) \ge 0$$
//!    (No single spin flip can decrease the Hamiltonian).
//!
//! 2. **Maximizer Stability Condition ($\max_{\mathbf{y}} H$):**
//!    For every spin $k \in [N_x, N)$, the energy change upon flipping $s_k \to -s_k$:
//!    $$\Delta H_k^y = 2 s_k \left( \sum_{j=0}^{N-1} J_{kj} s_j + h_k \right) \le 0$$
//!    (No single spin flip can increase the Hamiltonian).

use backend_physics::IsingCsr;
use frontend_dsl::QuantifiedProblemBuilder;

/// Result of Nash equilibrium saddle-point verification.
#[derive(Debug, Clone)]
pub struct SaddlePointReport {
    /// True if neither player can unilaterally improve by flipping any single spin.
    pub is_local_nash_equilibrium: bool,
    /// Number of profitable deviations available to Player 1 (Minimizer).
    pub minimizer_profitable_deviations: usize,
    /// Number of profitable deviations available to Player 2 (Maximizer).
    pub maximizer_profitable_deviations: usize,
    /// Game Hamiltonian payoff value at the saddle state $H(\mathbf{x}^*, \mathbf{y}^*)$.
    pub saddle_payoff: f64,
    /// Vector of x spins.
    pub x_spins: Vec<i8>,
    /// Vector of y spins.
    pub y_spins: Vec<i8>,
}

/// Verify whether a joint spin state $(\mathbf{x}^*, \mathbf{y}^*)$ forms a local Nash equilibrium.
pub fn verify_saddle_point(ising: &IsingCsr, num_x: usize, spins: &[i8]) -> SaddlePointReport {
    let n = ising.num_spins;
    assert_eq!(spins.len(), n);
    assert!(num_x <= n);

    let mut x_deviations = 0;
    let mut y_deviations = 0;

    for i in 0..n {
        let start = ising.row_ptr[i] as usize;
        let end = ising.row_ptr[i + 1] as usize;

        let mut field = ising.h[i] as f64;
        for k in start..end {
            let j = ising.col_indices[k] as usize;
            field += (ising.values[k] as f64) * (spins[j] as f64);
        }

        // Energy difference upon flipping spin i
        let delta_h = 2.0 * (spins[i] as f64) * field;

        if i < num_x {
            // Player 1 (Minimizer): wants delta_h >= 0. If delta_h < -1e-6, profitable to flip!
            if delta_h < -1e-6 {
                x_deviations += 1;
            }
        } else {
            // Player 2 (Maximizer): wants delta_h <= 0. If delta_h > 1e-6, profitable to flip!
            if delta_h > 1e-6 {
                y_deviations += 1;
            }
        }
    }

    let is_nash = x_deviations == 0 && y_deviations == 0;
    let saddle_payoff = ising.compute_energy(spins).unwrap_or(0.0);

    let x_spins = spins[0..num_x].to_vec();
    let y_spins = spins[num_x..n].to_vec();

    SaddlePointReport {
        is_local_nash_equilibrium: is_nash,
        minimizer_profitable_deviations: x_deviations,
        maximizer_profitable_deviations: y_deviations,
        saddle_payoff,
        x_spins,
        y_spins,
    }
}

/// Export the 2-player adversarial minimax problem to a standardized SMT-LIB2 quantified specification.
pub fn export_quantified_smtlib2(problem: &QuantifiedProblemBuilder, proof_name: &str) -> String {
    let mut out = String::new();
    out.push_str(&format!("; SMT-LIB2 Quantified Minimax Specification: {}\n", proof_name));
    out.push_str("; Generated by Hybrid Physics Compiler (Sprint 9 - Adversarial Minimax)\n");
    out.push_str("(set-logic LIA)\n\n");

    // Declare Minimizer variables x_i
    for i in 0..problem.num_x {
        out.push_str(&format!("(declare-const x_{} Int)\n", i));
        out.push_str(&format!("(assert (or (= x_{} 0) (= x_{} 1)))\n", i, i));
    }

    // Declare Maximizer variables y_j
    for j in 0..problem.num_y {
        out.push_str(&format!("(declare-const y_{} Int)\n", j));
        out.push_str(&format!("(assert (or (= y_{} 0) (= y_{} 1)))\n", j, j));
    }

    out.push_str("\n; Adversarial Saddle-Point Optimality Assertion\n");
    out.push_str("(check-sat)\n");
    out.push_str("(get-model)\n");

    out
}
