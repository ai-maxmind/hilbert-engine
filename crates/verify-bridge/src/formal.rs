//! Module `formal` defines the `FormalChecker` trait and SMT-LIB2 / Z3 export mechanisms.
//!
//! # Formal SMT-LIB2 Verification
//!
//! Translates high-level DSL problem constraints and candidate binary assignments
//! into verified SMT-LIB2 format compatible with theorem provers (Z3, CVC5, MathSAT).

use std::process::Command;
use thiserror::Error;
use frontend_dsl::constraints::Constraint;
use crate::decoder::{verify_constraints, VerificationReport};

#[derive(Debug, Error)]
pub enum FormalError {
    #[error("I/O error invoking SMT solver: {0}")]
    Io(#[from] std::io::Error),

    #[error("Z3 executable not found in PATH")]
    Z3NotFound,

    #[error("Z3 solver returned error: {0}")]
    Z3ExecutionError(String),
}

/// Outcome of invoking an SMT solver (e.g. Z3) on the exported problem.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Z3Result {
    /// Formula is satisfiable under the constraints and candidate assignment.
    Sat,
    /// Formula is proven unsatisfiable (contradiction / invalid assignment).
    Unsat,
    /// Solver timed out or returned unknown.
    Unknown(String),
    /// Z3 binary was not installed in the operating environment.
    NotAvailable,
}

/// Trait for formal verification and SMT-LIB2 specification export.
pub trait FormalChecker {
    /// Formally check a candidate binary assignment against all constraints.
    fn verify_solution(&self, assignment: &[u8]) -> VerificationReport;

    /// Export the problem specification and optional candidate assignment to standard SMT-LIB2.
    fn export_smtlib2(&self, candidate: Option<&[u8]>) -> String;

    /// Attempt to run Z3 directly on the generated SMT-LIB2 script if available in PATH.
    fn run_z3_check(&self, candidate: Option<&[u8]>) -> Result<Z3Result, FormalError>;
}

/// Standard formal verifier for combinatorial problems.
#[derive(Debug, Clone)]
pub struct ProblemVerifier {
    pub num_variables: usize,
    pub constraints: Vec<Constraint>,
}

impl ProblemVerifier {
    pub fn new(num_variables: usize, constraints: Vec<Constraint>) -> Self {
        Self {
            num_variables,
            constraints,
        }
    }
}

impl FormalChecker for ProblemVerifier {
    fn verify_solution(&self, assignment: &[u8]) -> VerificationReport {
        verify_constraints(&self.constraints, assignment)
    }

    fn export_smtlib2(&self, candidate: Option<&[u8]>) -> String {
        let mut smt = String::new();

        // 1. Header and logic definition
        smt.push_str("; ========================================================\n");
        smt.push_str("; SMT-LIB2 Benchmark Generated by Antigravity Hybrid Dynamics Compiler\n");
        smt.push_str("; ========================================================\n");
        smt.push_str("(set-logic QF_NIA)\n");
        smt.push_str("(set-info :source \"Antigravity Compiler - verify-bridge\")\n\n");

        // 2. Variable declarations: binary domain x_i in {0, 1}
        smt.push_str("; --- Variable Declarations (Domain: {0, 1}) ---\n");
        for i in 0..self.num_variables {
            smt.push_str(&format!("(declare-const x_{i} Int)\n"));
            smt.push_str(&format!("(assert (or (= x_{i} 0) (= x_{i} 1)))\n"));
        }
        smt.push('\n');

        // 3. Hard Constraint Assertions
        smt.push_str("; --- Problem Hard Constraints ---\n");
        for (idx, constraint) in self.constraints.iter().enumerate() {
            match constraint {
                Constraint::ExactOne { vars, .. } => {
                    let vars_str = vars
                        .iter()
                        .map(|v| format!("x_{v}"))
                        .collect::<Vec<_>>()
                        .join(" ");
                    smt.push_str(&format!("; Constraint {idx}: ExactOne({vars_str})\n"));
                    smt.push_str(&format!("(assert (= (+ {vars_str}) 1))\n"));
                }

                Constraint::And { x, y, out, .. } => {
                    smt.push_str(&format!("; Constraint {idx}: x_{out} = x_{x} AND x_{y}\n"));
                    smt.push_str(&format!("(assert (= x_{out} (* x_{x} x_{y})))\n"));
                }

                Constraint::Or { vars, .. } => {
                    let vars_str = vars
                        .iter()
                        .map(|v| format!("x_{v}"))
                        .collect::<Vec<_>>()
                        .join(" ");
                    smt.push_str(&format!("; Constraint {idx}: OR({vars_str})\n"));
                    smt.push_str(&format!("(assert (>= (+ {vars_str}) 1))\n"));
                }

                Constraint::Xor { x, y, out, .. } => {
                    smt.push_str(&format!("; Constraint {idx}: x_{out} = x_{x} XOR x_{y}\n"));
                    smt.push_str(&format!(
                        "(assert (= x_{out} (- (+ x_{x} x_{y}) (* 2 x_{x} x_{y}))))\n"
                    ));
                }

                Constraint::Clause3Sat { clause, .. } => {
                    let l1_str = if clause.l1.1 { format!("x_{}", clause.l1.0) } else { format!("(- 1 x_{})", clause.l1.0) };
                    let l2_str = if clause.l2.1 { format!("x_{}", clause.l2.0) } else { format!("(- 1 x_{})", clause.l2.0) };
                    let l3_str = if clause.l3.1 { format!("x_{}", clause.l3.0) } else { format!("(- 1 x_{})", clause.l3.0) };
                    smt.push_str(&format!("; Constraint {idx}: 3-SAT Clause\n"));
                    smt.push_str(&format!("(assert (>= (+ {l1_str} {l2_str} {l3_str}) 1))\n"));
                }
            }
        }
        smt.push('\n');

        // 4. Candidate Assignment Assertion (if provided)
        if let Some(cand) = candidate {
            smt.push_str("; --- Candidate Solution Verification ---\n");
            for (i, &val) in cand.iter().enumerate().take(self.num_variables) {
                smt.push_str(&format!("(assert (= x_{i} {val}))\n"));
            }
            smt.push('\n');
        }

        // 5. Query
        smt.push_str("(check-sat)\n");
        smt.push_str("(get-model)\n");

        smt
    }

    fn run_z3_check(&self, candidate: Option<&[u8]>) -> Result<Z3Result, FormalError> {
        let smt_script = self.export_smtlib2(candidate);

        // Attempt to invoke z3 with standard input
        use std::io::Write;
        let mut child = match Command::new("z3")
            .arg("-in")
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()
        {
            Ok(c) => c,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                return Ok(Z3Result::NotAvailable);
            }
            Err(e) => return Err(FormalError::Io(e)),
        };

        if let Some(mut stdin) = child.stdin.take() {
            stdin.write_all(smt_script.as_bytes())?;
        }

        let output = child.wait_with_output()?;
        let stdout = String::from_utf8_lossy(&output.stdout);

        if stdout.starts_with("sat") {
            Ok(Z3Result::Sat)
        } else if stdout.starts_with("unsat") {
            Ok(Z3Result::Unsat)
        } else {
            Ok(Z3Result::Unknown(stdout.to_string()))
        }
    }
}
